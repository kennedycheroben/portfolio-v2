import fs from "node:fs";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const distServerPath = path.resolve(__dirname, "dist-server/index.js");

// Fallback to source if running directly with experimental TypeScript support,
// or load compiled production bundle generated by 'npm run build'.
let serverModule;

if (fs.existsSync(distServerPath)) {
  serverModule = await import(pathToFileURL(distServerPath).href);
} else {
  // If dist-server hasn't been built yet, attempt to load src/server/index.ts
  const srcServerPath = path.resolve(__dirname, "src/server/index.ts");
  if (fs.existsSync(srcServerPath)) {
    try {
      serverModule = await import(pathToFileURL(srcServerPath).href);
    } catch {
      console.error(
        "\n[Startup Error] Compiled server bundle not found at 'dist-server/index.js'.\n" +
          "Please build the project first by running:\n\n" +
          "  npm run build\n\n" +
          "Then start the server with:\n\n" +
          "  npm start\n"
      );
      process.exit(1);
    }
  } else {
    console.error("[Startup Error] Unable to locate server entry point.");
    process.exit(1);
  }
}

const { startServer } = serverModule;

// Respect cPanel Passenger / environment assigned port
const port = process.env.PORT ? parseInt(process.env.PORT, 10) : 3000;
const host = process.env.HOST || "0.0.0.0";

const server = await startServer(port, host);

// Graceful shutdown
const shutdown = () => {
  console.log("\n[Server] Shutting down gracefully...");
  server.close(() => {
    console.log("[Server] Closed all active connections.");
    process.exit(0);
  });
};

process.on("SIGTERM", shutdown);
process.on("SIGINT", shutdown);
